import { describe, expect, it } from "vitest";
import { formatFileAttachment, formatManyFiles } from "./chatWire";
import { employeeWords, internalMessage, splitUserBubbleText } from "./userBubbleText";

const pdf = {
  kind: "file" as const,
  mimeType: "application/pdf",
  name: "20260807总经理办公会纪要③2026年第二次企业资质增补预算申请.pdf",
  sizeBytes: 1000,
  fileKind: "pdf",
  keptPath: "/Users/x/.catfish/uploads/1791879373-20260807总经理办公会纪要.pdf",
  previewText: "第一页正文……",
  meta: { pages: 4 },
};

describe("splitUserBubbleText", () => {
  it("10/13 截图那条: 气泡只剩员工的话, 附件变文件名", () => {
    const content = "就是这个会议纪要" + formatFileAttachment(pdf as never);
    const r = splitUserBubbleText(content);
    expect(r.text).toBe("就是这个会议纪要");
    expect(r.fileNames).toEqual([pdf.name]);
    expect(r.hidden).toContain("[完整文件:");
    for (const w of ["=== 附件", "完整文件", "preview", "execute_code", "/Users/"]) {
      expect(r.text).not.toContain(w);
    }
  });

  it("多文件紧凑模式也切得开, 文件名去重", () => {
    const files = Array.from({ length: 7 }, (_, i) => ({ ...pdf, name: `f${i}.pdf` }));
    const r = splitUserBubbleText("帮我核一下" + formatManyFiles(files as never));
    expect(r.text).toBe("帮我核一下");
    expect(r.fileNames).toHaveLength(7);
    expect(r.hidden.startsWith("\n\n[共 7 个文件。")).toBe(true);
  });

  it("微信聊天记录附件", () => {
    const content = "看看这段聊天\n\n=== 微信聊天记录: 达远智能 (120 条 · 10-01 ~ 10-12) ===\n--- 聊天记录 ---\n…";
    const r = splitUserBubbleText(content);
    expect(r.text).toBe("看看这段聊天");
    expect(r.fileNames).toEqual(["达远智能"]);
  });

  it("没有附件 / 只发了附件 / 空内容", () => {
    expect(splitUserBubbleText("普通一句话")).toEqual({ text: "普通一句话", hidden: "", fileNames: [], system: null });
    const onlyFile = splitUserBubbleText(formatFileAttachment(pdf as never));
    expect(onlyFile.text).toBe("");
    expect(onlyFile.fileNames).toEqual([pdf.name]);
    expect(splitUserBubbleText(undefined).text).toBe("");
  });

  it("压缩摘要里换行被吃掉, 附件标题直接接在话后面也认得出 (10/13 第二张截图)", () => {
    const s = "你核下附件1 的按照扣除的规则, 是不是只剩30？ === 附件: 关于2026年1-9月公司资质调用情况的通报(5).docx (Word · 39 段 · 10 表格) === [完整文件: /Users/x/a.docx]";
    const r = splitUserBubbleText(s);
    expect(r.text).toBe("你核下附件1 的按照扣除的规则, 是不是只剩30？");
    expect(r.fileNames).toEqual(["关于2026年1-9月公司资质调用情况的通报(5).docx"]);
  });

  it("整条是 hermes 以用户身份存的系统消息 → 一句灰字, 不当员工的话", () => {
    const cases: Array<[string, string]> = [
      ["[CONTEXT COMPACTION — REFERENCE ONLY] Earlier turns were compacted into the summary below.", "小鲶把前面的对话整理成了摘要"],
      ["[IMPORTANT: You are running as a scheduled cron job. DELIVERY: Your final response will be", "定时任务触发"],
      ['[IMPORTANT: The user has invoked the "daily-morning-brief" skill, indicating they want', "按技能「daily-morning-brief」执行"],
      ["[IMPORTANT: The following skill(s) were listed for this job but could not be found", "定时任务提示"],
      ["[ASYNC DELEGATION BATCH COMPLETE — deleg_x] A background fan-out of 1 subagent(s)", "后台子任务做完了"],
      ["[ASYNC DELEGATION COMPLETE — deleg_x] A background subagent you dispatched", "后台子任务做完了"],
      ["[System: Your previous response was truncated by the output length limit. Continue", "小鲶接着上次没说完的继续"],
      ["[System: The previous response was cut off by a network error mid-stream.", "小鲶接着上次没说完的继续"],
      ["[System: Your previous tool call (execute_code) was too large and the stream timed out", "小鲶接着上次没说完的继续"],
      ["[Your active task list was preserved across context compression]\n- [>] 3. x", "保留了进行中的任务清单"],
      ["<!-- catfish:advisor-sparse -->\n\n# 时间锚点\n今天: 6月16日", "早安顾问的准备材料"],
      ["# 时间锚点\n今天: 5月24日 星期日", "早安顾问的准备材料"],
      ["# 长期记忆 distilled_facts\n<!-- Generated by memory_distill -->", "整理长期记忆"],
      ["现在 09:00.\n\n日历: 今天没排事.\n邮件: 未读 5 封", "早安顾问的准备材料"],
      ["以下是员工跟 catfish AI 在某条待办 \"x\" 上的最近对话.\n\n用 100-150 字总结", "整理待办进展"],
      ["[System note: The previous turn was interrupted by a gateway shutdown; the gateway is now back online.]", "小鲶重启后接着之前的对话"],
    ];
    for (const [content, label] of cases) {
      const r = splitUserBubbleText(content);
      expect(r.system, content).toBe(label);
      expect(r.text).toBe("");
    }
  });

  it("员工的话前面粘的 [System note: …] 去掉, 图片路径行去掉", () => {
    const note = "[System note: Your previous turn was interrupted before you could process the last tool result(s). Please finish processing those results, then address the user's new message below.]\n\n";
    expect(splitUserBubbleText(note + "你再试一次")).toMatchObject({ text: "你再试一次", system: null });
    const img = "[System note: A new message has arrived. Address the user's NEW message below FIRST.]\n\n[Image attached at: /Users/x/.hermes/image_cache/img_1.jpg]\n[screenshot]";
    const r = splitUserBubbleText(img);
    expect(r.text).toBe("🖼 截图");
    expect(r.text).not.toContain("/Users/");
  });

  it("员工的话以 ] 结尾不会被当成系统消息吞掉", () => {
    const note = "[System note: Address the user's new message below.]\n\n";
    expect(splitUserBubbleText(note + "看 [[福富资质]]")).toMatchObject({ text: "看 [[福富资质]]", system: null });
    expect(splitUserBubbleText("[[福富资质]]").system).toBeNull();
  });

  it("员工自己正文里提到「附件」不会被误切", () => {
    const s = "附件: 我昨天发的那个报价单, 你再看看 === 附件 这几个字";
    expect(splitUserBubbleText(s).text).toBe(s);
  });

  it("10/16: 每轮通知粘在员工的话后面 (技能清单变了), 气泡里不显示", () => {
    const note = "[System: The skills available in this conversation changed after its system prompt was built.\n" +
      "Now available (load with skill_view(name) when relevant, like the skills listed in the system prompt):\n" +
      "    - procurement-doc-review: 复核代理回稿的采购方案与评审表\n" +
      "    - video-audio-summary: 员工丢来本机视频/音频文件要摘要]";
    const r = splitUserBubbleText("把这段描述改下, 改成对应部门名称:\n🖼 截图\n\n" + note);
    expect(r.text).toBe("把这段描述改下, 改成对应部门名称:\n🖼 截图");
    expect(r.system).toBeNull();
    for (const w of ["[System:", "skill_view", "procurement-doc-review"]) expect(r.text).not.toContain(w);
  });

  it("10/16: 换界面 / 插件上线这类通知同样剥掉; 整条都是通知时显示成系统提示", () => {
    const switched = splitUserBubbleText("继续\n\n[System: This conversation is now being answered on a different interface: 微信]");
    expect(switched.text).toBe("继续");
    expect(splitUserBubbleText("[System: The skills available in this conversation changed.]").system).toBe("系统提示");
    // 员工自己打的 [System: ...] 后面还有话 → 不动
    const typed = "帮我看下这行日志 [System: boom] 是什么意思";
    expect(splitUserBubbleText(typed).text).toBe(typed);
  });

  it("10/16 下午: <memory-context> 召回记忆 (带 4 张图那条), 气泡里只剩员工的话", () => {
    // state.db 里的真实形状: 员工的话 → [screenshot] ×4 → 注入块
    const content = [
      "依据视频的内容写一个学习简报, 要把四张图片纳入, 文字不超过800字",
      "[screenshot]\n[screenshot]\n[screenshot]\n[screenshot]",
      "<memory-context>\n[System note: The following is recalled memory context, NOT new user input.]\n\n" +
        "## 员工身份与目的\n你服务的员工: 陈鸿波\n</memory-context>",
    ].join("\n\n");
    const r = splitUserBubbleText(content);
    expect(r.text).toBe("依据视频的内容写一个学习简报, 要把四张图片纳入, 文字不超过800字\n\n🖼 截图\n🖼 截图\n🖼 截图\n🖼 截图");
    for (const w of ["memory-context", "System note", "陈鸿波"]) expect(r.text).not.toContain(w);
  });

  it("通用判据: 没见过的注入物也能扔 (不用再加名字)", () => {
    // 这三种今天都还不存在, 靠形状认: XML 围栏 / [Word 方括号 / 多块叠加
    const future = "帮我看下这个\n\n<tool-budget>\n剩余 3 次\n</tool-budget>";
    expect(splitUserBubbleText(future).text).toBe("帮我看下这个");
    const bracket = "帮我看下这个\n\n[Workspace changed: 3 files]";
    expect(splitUserBubbleText(bracket).text).toBe("帮我看下这个");
    const stacked = "帮我看下这个\n\n<memory-context>\nx\n</memory-context>\n\n[System: skills changed]\n\n[Surface: 微信]";
    expect(splitUserBubbleText(stacked).text).toBe("帮我看下这个");
  });

  it("通用判据不能误伤员工写的东西", () => {
    // 中文方括号 / 编号 / 行内英文方括号 —— 都不是机器块
    for (const t of [
      "[图片] 这是什么意思",
      "两点:\n\n[1] 先报价\n\n[2] 再谈判",
      "帮我看下这行日志 [System: boom] 是什么意思",
      "报价单模板里写 {{客户}}\n\n<br> 要不要去掉",  // <br> 后面还有话, 不是整块
    ]) {
      expect(splitUserBubbleText(t).text).toBe(t);
    }
  });

  it("整条都是注入物 (这轮只发了图, 一个字没写) → 系统提示", () => {
    expect(splitUserBubbleText("<memory-context>\nx\n</memory-context>").system).toBe("系统提示");
  });

  it("10/16 第二次踩: 消息超 4000 字被截断, 注入块没有收尾标签也要切掉", () => {
    // sessions.rs::truncate 把长消息截断再给界面 —— 这条真实消息 9873 字, 界面只拿到前 4000 字,
    // </memory-context> 根本没进来。按开头切才不依赖收尾。
    const injected = "<memory-context>\n[System note: recalled memory context]\n\n## 员工身份\n" + "细节 ".repeat(500);
    const content = `依据视频的内容写一个学习简报\n[screenshot]\n${injected}`;
    const truncated = `${[...content].slice(0, 4000).join("")}\n\n…（已截断，原长度 ${[...content].length} 字符）`;
    expect(truncated).not.toContain("</memory-context>");  // 前提: 收尾标签确实不在
    const r = splitUserBubbleText(truncated);
    expect(r.text).toBe("依据视频的内容写一个学习简报\n🖼 截图");
    expect(r.text).not.toContain("已截断");
  });
});


/** 10/25 鸿波截图: hermes 压缩上下文后自己写进历史的标记漏进了对话。
 *  文字照抄 hermes-agent agent/context_compressor.py (不是真聊天记录)。 */
describe("internalMessage · hermes 压缩标记", () => {
  const SUMMARY = "[CONTEXT COMPACTION — REFERENCE ONLY] Earlier turns were compacted into the summary below. 员工在弄高新申报材料";
  const MERGED =
    "[PRIOR CONTEXT — for reference only; not a new message]\n好的，先结束教学 session 然后直接凝固。\n\n" +
    "[END OF PRIOR CONTEXT — COMPACTION SUMMARY BELOW]\n\n" + SUMMARY;
  const PLACEHOLDER =
    "Continue from the compressed conversation context above. This marker exists because no human user turn was available.";
  const LEGACY_PLACEHOLDER =
    "Continue from the compressed conversation context above. This marker exists because the compacted " +
    "transcript contained no preserved user turn.";

  it("压缩占位「用户消息」整条不显示 (新老两版文字), 不管有没有打标记", () => {
    for (const content of [PLACEHOLDER, LEGACY_PLACEHOLDER]) {
      expect(internalMessage({ role: "user", content })).toEqual({ hidden: true });
      expect(internalMessage({ role: "assistant", content })).toEqual({ hidden: true });
    }
  });

  it("没打 _compressed_summary 的摘要: user / assistant 两边都显示成一行说明", () => {
    const note = { hidden: false, label: "小鲶把前面的对话整理成了摘要" };
    expect(internalMessage({ role: "user", content: SUMMARY })).toEqual(note);
    expect(internalMessage({ role: "assistant", content: SUMMARY })).toEqual(note);
    expect(internalMessage({ role: "assistant", content: MERGED })).toEqual(note);
    expect(internalMessage({ role: "user", content: MERGED })).toEqual(note);
    expect(internalMessage({ role: "assistant", content: "[CONTEXT SUMMARY]: 老版摘要" })).toEqual(note);
  });

  it("hermes 打的标记优先", () => {
    expect(internalMessage({ role: "assistant", content: "随便", displayKind: "hidden" })).toEqual({ hidden: true });
    expect(internalMessage({ role: "assistant", content: MERGED, displayKind: "compaction" })?.hidden).toBe(false);
  });

  it("工具轮数到上限时 hermes 替员工发的「请小结」不当员工的话", () => {
    const r = internalMessage({
      role: "user",
      content: "You've reached the maximum number of tool-calling iterations allowed. Please provide a final response",
    });
    expect(r).toEqual({ hidden: false, label: "工具调用次数到上限了, 小鲶先做个小结" });
  });

  it("正常对话不误伤: 员工 / 小鲶话里提到这些词照常显示", () => {
    expect(internalMessage({ role: "user", content: "[CONTEXT COMPACTION 是什么意思?" })?.hidden).toBe(false); // 开头一样就认, 跟老规则一致
    expect(internalMessage({ role: "user", content: "日志里有 [CONTEXT COMPACTION — REFERENCE ONLY] 是啥" })).toBeNull();
    expect(internalMessage({ role: "assistant", content: "你看到的「Continue from the compressed…」是 hermes 的占位" })).toBeNull();
    expect(internalMessage({ role: "assistant", content: "[1] 先报价" })).toBeNull();
    expect(internalMessage({ role: "user", content: "帮我改一下方案" })).toBeNull();
  });

  it("员工话后面接的压缩保留任务清单切掉 (标记头超过 30 字, 单独认)", () => {
    const content =
      "继续\n\n[Your active task list was preserved across context compression]\n- [>] 5. 新建概念 (in_progress)\n- [ ] 6. 验证 (pending)";
    expect(splitUserBubbleText(content).text).toBe("继续");
    expect(employeeWords({ role: "user", content })).toBe("继续");
    expect(splitUserBubbleText("[Skills pruned during compression — reload before acting on these tasks]\n- x").system).toBe("系统提示");
  });

  it("employeeWords: 只有员工的消息给出气泡里那段话, 其余 null", () => {
    expect(employeeWords({ role: "user", content: "就是这个会议纪要" + formatFileAttachment(pdf as never) })).toBe("就是这个会议纪要");
    expect(employeeWords({ role: "user", content: SUMMARY })).toBeNull();
    expect(employeeWords({ role: "user", content: PLACEHOLDER })).toBeNull();
    expect(employeeWords({ role: "assistant", content: "好的" })).toBeNull();
  });
});

/** 10/25 鸿波装了 1.1.73 「还是一样的」: 1.1.73 之前生成、已经存进历史的催问还在显示 */
describe("internalMessage · 引用了内部标记的老催问", () => {
  it("沉默 / 切回两种模板, 引号里是压缩摘要或占位 → 整条不显示", () => {
    for (const content of [
      '640 分钟没动静了。你刚说"[CONTEXT COMPACTION — REFERENCE ONLY] Ea...", 现在还在弄吗? 卡哪我帮看看.',
      '回来啦, 129 分钟没见。刚才你说"[CONTEXT COMPACTION — REFERENCE ONLY] Ea", 还在等我跟进吗?',
      '30 分钟没动静了。你刚说"Continue from the compressed conversati...", 现在还在弄吗? 卡哪我帮看看.',
      '回来啦, 45 分钟没见。刚才你说"[PRIOR CONTEXT — for reference only; not", 还在等我跟进吗?',
    ]) {
      expect(internalMessage({ role: "assistant", content })).toEqual({ hidden: true });
    }
  });

  it("引用员工真话的催问照常显示; 不是模板的不认", () => {
    expect(
      internalMessage({ role: "assistant", content: '640 分钟没动静了。你刚说"我去弄一下申报材料", 现在还在弄吗? 卡哪我帮看看.' }),
    ).toBeNull();
    expect(internalMessage({ role: "assistant", content: '你刚说"[CONTEXT COMPACTION — REFERENCE ONLY]" 是 hermes 的压缩标记' })).toBeNull();
    // 员工的消息长这样不归这条管
    expect(
      internalMessage({ role: "user", content: '回来啦, 129 分钟没见。刚才你说"[CONTEXT COMPACTION — REFERENCE ONLY] Ea", 还在等我跟进吗?' }),
    ).toBeNull();
  });
});
