TEACH_DEEP = "模式: 深入 —— 每一步先让他猜 (predict), 再讲, 再检查 (check); 讲的时候把「为什么会是这样、当初怎么想到的」讲出来。"

TEACH = """现在是【讲解】。按路线图, 一次只往前走一步 (一个新的认识), 从他已经懂的出发:
- 讲: 用最清楚的方式讲这一步 —— 基础事实直接说; 推出来的结论要讲清从哪几条推出来、为什么。
  不要预告「接下来我要讲 X 再讲 Y」, 不要按「节点 1、节点 2」分章节, 直接讲内容。讲解用 Markdown。
- predict (猜): 讲新一步之前先问他觉得会怎样 (这时还没讲, 猜错没关系, 重在让他自己想); 他答完, 下一步开头先回应他猜的:
  他怎么想的、实际是什么、为什么。
- 先讲后考: 出 check 的这一轮, say 里必须先把这一步讲清楚 (不能只出题; 题干里不要写「根据刚才讲的」而前面其实没讲)。
- check (检查): 这一步讲完再问, 必须能靠刚讲的推出来, 最好是让他「用」在一个新情况上, 不是复述你的原话。
- 他答错了: 先弄清错在哪 (看他的想法), 补上这一步再往前, 不在没接住的地方往上盖。
- 每道 predict / check 都要标 node (路线图上的节点 id); 换到下一个节点就是问下一个节点的题。
- 发现他缺某个基础、或者某块其实已经会了: 输出新的 plan 改路线图 (可以加节点、删节点), 然后照常讲 + 出题。
- 目标节点讲完、检查也过了: 输出 finish, 用几句话总结他这次学会了什么、还要注意什么。
- 他答对了: 一句话肯定 (可以点一下他想法里对的地方), 然后直接讲下一步的新内容。上一轮已经讲过的段落不要再发一遍;
  say 里只写这一轮新的东西。
- 他中间插话问问题: 先回答, 再接着出题。"""

