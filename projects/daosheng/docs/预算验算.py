#!/usr/bin/env python3
"""daosheng 预算验算 —— 三张投入表必须互相闭合。

8/6 更新：GPU 由 2 台放大到 6 台（2.4T 级模型 FP8 双实例），硬件、托管、可申报占比全部重算。
硬件一次性在阶段一采购（8/6 鸿波定，不分批）。互联 fabric 查到的挂牌价折算为 96–248 万，
表内保留原估 150–350 万作为余量（挂牌价不含进口环节、集成与安装）。

8/6 起因：鸿波指出「投入·分阶段这张表加起来不对」。
查下来数字本身是对的，但表上只列了 6 项成本里的 3 项，
阶段一 103+100+140=343 对小计 1,020，差三倍且读者无从核对。
补列时顺带发现 P17 政策页「服务费与其他」写成 617–1,121，
应为 472–1,121（147+325 / 501+620），该列不合计，差 145 万。

改任何一个数字后跑一遍：  python3 docs/预算验算.py
"""

# ── P15 投入·构成 ────────────────────────────────────────────
构成 = {
    "运营人力":       (1270, 2094),
    "平台开发":  (490, 1252),
    "硬件采购":       (1845, 2455),
    "应用开发":       (400, 980),
    "平台年服务费":    (147, 501),
    "其他·托管·培训":  (415, 890),
    "安全与合规":     (90, 250),      # 等保三级（8/6 鸿波定）
}
静态投资 = (4657, 8422)
总额 = 静态投资            # 下面各表的「小计 / 合计」仍按静态口径闭合

# ── 基本预备费（8/6 补）──────────────────────────────────────
# 鸿波：「总价怎么没有变？」—— 原先只在 P15 写了「另计 650 万 / 立项 7,000 万」，
# 另外三页的合计一动没动，五页口径打架。按国内投资估算的通行结构：
#     静态投资 ＋ 基本预备费 ＝ 项目总投资
# 预备费是总投资的组成部分，不是「另计」。按科目分档计提，两端各算各的。
计提率 = {"硬件采购": 0.10, "运营人力": 0.05, "平台开发": 0.15,
          "应用开发": 0.15, "平台年服务费": 0.15, "其他·托管·培训": 0.10,
          "安全与合规": 0.10}
预备费 = (455, 875)
项目总投资 = (5112, 9297)

# ── P16 投入·分阶段（七列，行列均须闭合）──────────────────────
分阶段 = {
    #            人力         应用开发      平台开发      硬件        服务费与其他
    "阶段一": [(103, 167),  (100, 210), (140, 405), (1845, 2455), (67, 142), (60, 160)],
    "阶段二": [(416, 682),  (200, 490), (300, 721), (0, 0),       (182, 462), (15, 45)],
    "阶段三": [(751, 1245), (100, 280), (50, 126),  (0, 0),       (313, 787), (15, 45)],
}
小计 = {"阶段一": (2315, 3539), "阶段二": (1113, 2400), "阶段三": (1229, 2483)}

# ── P17 投入·政策可申报 ──────────────────────────────────────
政策 = {
    "硬件采购":        ((1845, 2455), True),
    "平台开发（买断＋委托）":  ((490, 1252), True),
    "应用开发":        ((400, 980), True),   # 部分可申报，按全额计入可申报基数
    "安全与合规":      ((90, 250), True),    # 等保建设属专项明确支持方向
    "运营人力":        ((1270, 2094), False),
    "服务费与其他":     ((562, 1391), False),
}
可申报合计 = (2825, 4937)

fails = []


def add(*pairs):
    return (sum(p[0] for p in pairs), sum(p[1] for p in pairs))


def check(label, got, want):
    ok = got == want
    print(f"  {'✓' if ok else '✗'} {label:34} {got[0]:>6,}–{got[1]:<6,}  期望 {want[0]:>6,}–{want[1]:<6,}")
    if not ok:
        fails.append(label)


print("【一】P15 投入·构成 —— 六项须等于总额")
check("六项相加", add(*构成.values()), 总额)

print("\n【二】P16 投入·分阶段 —— 逐行闭合（这是 8/6 补列的理由）")
for st, cols in 分阶段.items():
    check(f"{st} 五列相加 = 小计", add(*cols), 小计[st])

print("\n【三】P16 逐列闭合 —— 须等于 P15 对应科目")
服务费与其他 = add(构成["平台年服务费"], 构成["其他·托管·培训"])
列名 = ["运营人力", "应用开发", "平台开发", "硬件采购", "服务费与其他", "安全与合规"]
for i, n in enumerate(列名):
    列 = add(*[分阶段[st][i] for st in 分阶段])
    check(f"列 {n}", 列, 构成.get(n, 服务费与其他))
check("列 小计", add(*小计.values()), 总额)

print("\n【四】P17 政策 —— 五项须等于总额，可申报三项须等于合计")
check("五项相加", add(*[v[0] for v in 政策.values()]), 总额)
check("可申报三项", add(*[v[0] for v in 政策.values() if v[1]]), 可申报合计)

print("\n【五】跨页一致性 —— P17 各科目须与 P15 对齐")
check("P17 硬件 = P15 硬件", 政策["硬件采购"][0], 构成["硬件采购"])
check("P17 平台 = P15 平台", 政策["平台开发（买断＋委托）"][0], 构成["平台开发"])
check("P17 外包 = P15 外包", 政策["应用开发"][0], 构成["应用开发"])
check("P17 人力 = P15 人力", 政策["运营人力"][0], 构成["运营人力"])
check("P17 服务费与其他 = 年服务费+其他", 政策["服务费与其他"][0], 服务费与其他)

print("\n【六】占比 —— 按中值计，最大余额法配平，须恰好 100%")
# 原来是 39/20/19/14/7/10 合 109%：各行分母不一致（有的按下限、有的按上限、
# 有的按中值）。这里统一按中值算，再用最大余额法把舍入差摊掉。
表内占比 = {"运营人力": 26, "平台开发": 13, "硬件采购": 33,
            "应用开发": 10, "平台年服务费": 5, "其他·托管·培训": 10, "安全与合规": 3}
中值 = {n: (lo + hi) / 2 for n, (lo, hi) in 构成.items()}
总中值 = sum(中值.values())
精确 = {n: v / 总中值 * 100 for n, v in 中值.items()}
配平 = {n: int(v) for n, v in 精确.items()}
for n in sorted(精确, key=lambda k: -(精确[k] - int(精确[k])))[: 100 - sum(配平.values())]:
    配平[n] += 1
for n in 构成:
    ok = 配平[n] == 表内占比[n]
    if not ok:
        fails.append(f"占比 {n}")
    print(f"  {'✓' if ok else '✗'} {n:16} 精确 {精确[n]:5.2f}%  配平 {配平[n]:>2}%  表内 {表内占比[n]:>2}%")
print(f"  {'—— 配平合计':18} {sum(配平.values())}%   表内合计 {sum(表内占比.values())}%")
if sum(表内占比.values()) != 100:
    fails.append("占比合计 ≠ 100%")
print(f"  中值总额 {总中值:,.0f} 万（静态口径，表内占比按此计）")
print(f"\n  可申报占比 {可申报合计[0] / 总额[0]:.0%} – {可申报合计[1] / 总额[1]:.0%}（表内写「约占静态投资六成」）")

print("\n【七】基本预备费与项目总投资")
计 = (sum(round(构成[k][0] * r) for k, r in 计提率.items()),
      sum(round(构成[k][1] * r) for k, r in 计提率.items()))
check("分档计提之和 = 预备费", 计, 预备费)
check("静态 ＋ 预备费 = 项目总投资", add(静态投资, 预备费), 项目总投资)
for k, r in 计提率.items():
    print(f"      {k:16}{构成[k][0]:>6,}–{构成[k][1]:<6,} × {r:.0%} → "
          f"{round(构成[k][0]*r):>4}–{round(构成[k][1]*r):<4}")
print(f"      预备费占静态 {预备费[0]/静态投资[0]:.1%}–{预备费[1]/静态投资[1]:.1%}"
      f"   项目总投资中值 {(项目总投资[0]+项目总投资[1])/2:,.0f} 万（表内写「约 7,200 万」）")

print()
if fails:
    print(f"✗ {len(fails)} 项不闭合：" + "、".join(fails))
    raise SystemExit(1)
print("✓ 三张投入表行列全部闭合")
