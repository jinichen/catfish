function bullet(text, level = 0) {
  return new Paragraph({
    numbering: { reference: "dot", level },
    spacing: { after: 80, line: 300 },
    children: [new TextRun({ text, size: 21, font: FONT })],
  });
}

function cell(text, o = {}) {
  const { bold, shade, w, align } = o;
  return new TableCell({
    width: { size: w, type: WidthType.DXA },
    shading: shade ? { type: ShadingType.CLEAR, fill: shade, color: "auto" } : undefined,
    margins: { top: 80, bottom: 80, left: 120, right: 120 },
    children: [new Paragraph({
      alignment: align,
      spacing: { after: 0, line: 260 },
      children: [new TextRun({ text, bold, size: 19, font: FONT })],
    })],
  });
}

function table(widths, header, rows) {
  const total = widths.reduce((a, b) => a + b, 0);
  const scale = W / total;
  const cw = widths.map(x => Math.round(x * scale));
  cw[cw.length - 1] = W - cw.slice(0, -1).reduce((a, b) => a + b, 0);
  return new Table({
    columnWidths: cw,
    width: { size: W, type: WidthType.DXA },
    rows: [
      new TableRow({
        tableHeader: true,
        children: header.map((t, i) => cell(t, { bold: true, shade: ACCENT, w: cw[i] })),
      }),
      ...rows.map((r, ri) => new TableRow({
        children: r.map((t, i) => cell(t, { w: cw[i], shade: ri % 2 ? GREY : undefined })),
      })),
    ],
  });
}
// 表头文字要白 —— 上面 cell() 统一黑, 这里覆写
function tableWhiteHead(widths, header, rows) {
  const total = widths.reduce((a, b) => a + b, 0);
  const scale = W / total;
  const cw = widths.map(x => Math.round(x * scale));
  cw[cw.length - 1] = W - cw.slice(0, -1).reduce((a, b) => a + b, 0);
  return new Table({
    columnWidths: cw,
    width: { size: W, type: WidthType.DXA },
    rows: [
      new TableRow({
        tableHeader: true,
        children: header.map((t, i) => new TableCell({
          width: { size: cw[i], type: WidthType.DXA },
          shading: { type: ShadingType.CLEAR, fill: ACCENT, color: "auto" },
          margins: { top: 80, bottom: 80, left: 120, right: 120 },
          children: [new Paragraph({
            spacing: { after: 0, line: 260 },
            children: [new TextRun({ text: t, bold: true, size: 19, color: "FFFFFF", font: FONT })],
          })],
        })),
      }),
      ...rows.map((r, ri) => new TableRow({
        children: r.map((t, i) => cell(t, { w: cw[i], shade: ri % 2 ? GREY : undefined })),
      })),
    ],
  });
}

function callout(title, lines) {
  return new Table({
    columnWidths: [W],
    width: { size: W, type: WidthType.DXA },
    borders: {
      top: { style: BorderStyle.SINGLE, size: 2, color: "C9D6DD" },
      bottom: { style: BorderStyle.SINGLE, size: 2, color: "C9D6DD" },
      left: { style: BorderStyle.SINGLE, size: 18, color: ACCENT },
      right: { style: BorderStyle.SINGLE, size: 2, color: "C9D6DD" },
      insideHorizontal: { style: BorderStyle.NONE },
      insideVertical: { style: BorderStyle.NONE },
    },
    rows: [new TableRow({
      children: [new TableCell({
        width: { size: W, type: WidthType.DXA },
        shading: { type: ShadingType.CLEAR, fill: GREY, color: "auto" },
        margins: { top: 140, bottom: 140, left: 180, right: 180 },
        children: [
          new Paragraph({
            spacing: { after: 80, line: 280 },
            children: [new TextRun({ text: title, bold: true, size: 21, color: ACCENT, font: FONT })],
          }),
          ...lines.map(t => new Paragraph({
            spacing: { after: 60, line: 280 },
            children: [new TextRun({ text: t, size: 20, font: FONT })],
          })),
        ],
      })],
    })],
  });
}

