function card(s, x, y, w, h, opt) {
  const { title, lines, color = C.primary, fill = C.white, big } = opt;
  s.addShape(p.ShapeType.rect, { x, y, w, h, fill: { color: fill }, line: { color: "E3E3DE", width: 0.75 } });
  s.addShape(p.ShapeType.rect, { x, y, w: 0.055, h, fill: { color } });
  let cy = y + 0.16;
  if (title) { s.addText(title, { x: x + 0.22, y: cy, w: w - 0.4, h: 0.32, fontSize: 13, bold: true, color, fontFace: F, margin: 0 }); cy += 0.4; }
  if (big) { s.addText(big, { x: x + 0.22, y: cy, w: w - 0.4, h: 0.42, fontSize: 19, bold: true, color: C.dark, fontFace: F, margin: 0 }); cy += 0.5; }
  if (lines && lines.length) {
    s.addText(lines.map((t) => ({ text: t, options: { bullet: { code: "2022" }, breakLine: true } })), {
      x: x + 0.22, y: cy, w: w - 0.4, h: y + h - cy - 0.14,
      fontSize: 10.5, color: C.gray, fontFace: F, lineSpacing: 16, margin: 0, valign: "top" });
  }
}

function table(s, x, y, w, cols, rows, opt = {}) {
  const colW = cols.map((c) => (c.w / 100) * w);
  s.addTable(
    [cols.map((c) => ({ text: c.t, options: { bold: true, color: C.white, fill: { color: C.primary }, fontSize: 10.5 } })),
     ...rows.map((r, i) => r.map((t) => ({ text: t, options: { fontSize: 10, color: C.dark, fill: { color: i % 2 ? C.bg2 : C.white } } })))],
    { x, y, w, colW, fontFace: F, border: { pt: 0.5, color: "E3E3DE" }, rowH: opt.rowH || 0.34, valign: "middle", margin: 0.06 });
}

