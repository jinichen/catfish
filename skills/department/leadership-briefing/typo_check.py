def _build_pairs() -> dict[str, tuple[str, str]]:
    """构建 错→(对, 类别) 字典. 跳过 'X→X 通用 - 跳过' 的占位."""
    pairs: dict[str, tuple[str, str]] = {}
    for wrong, correct, category in TYPO_PAIRS:
        if wrong == correct:
            continue  # 跳过占位
        if "跳过" in category:
            continue
        pairs[wrong] = (correct, category)
    return pairs


_PAIRS_CACHE = _build_pairs()


def correct(text: str) -> dict[str, Any]:
    """检测错别字, 返回 {source, target, errors}.

    跟 pycorrector.Corrector.correct() 接口兼容, 调用方不用改.

    `errors` 格式: [{"old": "帐户", "new": "账户", "pos": 12, "category": "财务术语"}]
    """
    errors: list[dict[str, Any]] = []
    target = text

    for wrong, (correct_word, category) in _PAIRS_CACHE.items():
        # 找所有出现位置
        for m in re.finditer(re.escape(wrong), text):
            errors.append({
                "old": wrong,
                "new": correct_word,
                "pos": m.start(),
                "category": category,
            })

        if wrong in target:
            target = target.replace(wrong, correct_word)

    # 按位置排序, 方便阅读
    errors.sort(key=lambda e: e["pos"])

    return {
        "source": text,
        "target": target,
        "errors": errors,
    }


